/** Supabase usa CA própria; outros bancos usam as CAs públicas do sistema. */
export function ehHostSupabase(url: string): boolean {
  try {
    const h = new URL(url).hostname;
    return h.endsWith(".supabase.com") || h.endsWith(".supabase.co");
  } catch {
    return false;
  }
}
